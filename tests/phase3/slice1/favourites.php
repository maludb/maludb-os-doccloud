<?php
/** Slice 1 proof — favourites and recents: a folder and a document starred, listed, the star on the folder page, removed; Recent lists a seeded document once opened (spec "Proof" 11). */
require __DIR__ . '/lib.php';
$seed = seed_store();
$priyaRoot = root_of(26);
echo "1. Favourites\n";
$b = page(actor(26), '/favourites')['body'];
ok(str_contains($b, 'Star a folder or a document'), 'the empty favourites say what to do');
$r = post(26, '/favourites/add.php', ['folder' => $seed['contracts']]);
ok($r['code'] === 302 && str_ends_with($r['location'], '/f/' . $seed['contracts'] . '?notice=starred') && one('SELECT count(*) FROM favourites WHERE member_id = 26 AND folder_id = :f', ['f' => $seed['contracts']]) === 1, 'favourite_add stars a folder and lands back on it');
$r = post(26, '/favourites/add.php', ['document' => $seed['board_doc'], 'return_to' => '/favourites']);
ok($r['code'] === 302 && str_ends_with($r['location'], '/favourites?notice=starred') && one('SELECT count(*) FROM favourites WHERE member_id = 26 AND document_id = :d', ['d' => $seed['board_doc']]) === 1, 'favourite_add stars a document');
$r = post(26, '/favourites/add.php', ['document' => $seed['board_doc']]);
ok($r['code'] === 302 && one('SELECT count(*) FROM favourites WHERE member_id = 26') === 2, 'starring twice adds nothing');
$r = post(26, '/favourites/add.php', ['document' => $seed['board_doc'], 'folder' => $seed['contracts']]);
ok($r['code'] === 422 && str_contains($r['body'], 'one of them'), 'a document or a folder, one of them');
$r = post(26, '/favourites/add.php', ['document' => $seed['guest_doc']]);
ok($r['code'] === 404, 'a document the caller may not see: Not found');
$r = post(29, '/favourites/add.php', ['document' => $seed['guest_doc']]);
ok($r['code'] === 302 && one('SELECT count(*) FROM favourites WHERE member_id = 29') === 1, 'the guest stars the one document shared with her');
$ev = last_event('favourite.add');
ok((int) $ev['document_id'] === $seed['guest_doc'] && (int) $ev['actor_member_id'] === 29, 'favourite.add logged with the document');
$b = page(actor(26), '/favourites')['body'];
ok(str_contains($b, 'id="listing-row-folder-' . $seed['contracts'] . '"') && str_contains($b, 'id="listing-row-document-' . $seed['board_doc'] . '"') && strpos($b, 'listing-row-folder-') < strpos($b, 'listing-row-document-'), 'Favourites lists the folder then the document');
ok(str_contains($b, 'id="favourite-remove-folder-' . $seed['contracts'] . '"'), '...each with a Remove button');
$b = page(actor(26), '/f/' . $seed['contracts'])['body'];
ok(str_contains($b, 'id="folder-star-btn"') && str_contains($b, 'feather-star text-warning') && str_contains($b, 'action="/favourites/remove.php"'), 'the folder page shows the star lit and offers to unstar');
$b = page(actor(26), '/f/' . $seed['board_root'])['body'];
ok(preg_match('/id="listing-row-folder-' . $seed['contracts'] . '".*?feather-star text-warning/s', $b) === 1, 'the listing marks the starred folder');
$b = page(actor(26), '/favourites', ['headers' => ['Accept: application/json']])['body'];
$j = json_decode($b, true);
ok(count($j['data']['rows'] ?? []) === 2 && ($j['data']['rows'][0]['kind'] ?? '') === 'folder' && isset($j['data']['rows'][0]['starred_at']), 'the JSON lists two rows with starred_at');
$r = post(26, '/favourites/remove.php', ['folder' => $seed['contracts'], 'return_to' => '/favourites']);
ok($r['code'] === 302 && str_ends_with($r['location'], '/favourites?notice=unstarred') && one('SELECT count(*) FROM favourites WHERE member_id = 26') === 1 && last_event('favourite.remove') !== null, 'favourite_remove unstars and logs');
$r = post(26, '/favourites/remove.php', ['folder' => $seed['contracts']]);
ok($r['code'] === 404 && str_contains($r['body'], 'Not a favourite of yours'), 'removing again: not a favourite');
$r = post(27, '/favourites/remove.php', ['document' => $seed['board_doc']]);
ok($r['code'] === 404, 'one cannot remove another\'s star');
ok(!str_contains(page(actor(26), '/favourites')['body'], 'listing-row-folder-' . $seed['contracts']), 'the folder is gone from Favourites');

echo "2. Recent\n";
$b = page(actor(26), '/recent')['body'];
ok(str_contains($b, 'id="listing-row-document-' . $seed['priya_doc'] . '"'), 'Recent lists Priya\'s own document');
pdo()->prepare('UPDATE documents SET last_opened_at = now() WHERE id = :d')->execute(['d' => $seed['board_doc']]);
$b = page(actor(26), '/recent')['body'];
ok(str_contains($b, 'id="listing-row-document-' . $seed['priya_doc'] . '"'), '...and still after another was opened (recents are one\'s own and what one opened)');
$j = json_decode(page(actor(26), '/recent', ['headers' => ['Accept: application/json']])['body'], true);
ok(isset($j['data']['rows']) && is_array($j['data']['rows']) && array_key_exists('last_opened_at', $j['data']['rows'][0] ?? ['last_opened_at' => null]), 'the JSON carries last_opened_at');
ok(page(actor(29), '/recent')['code'] === 403, 'a guest has no Recent (no personal library)');
finish();

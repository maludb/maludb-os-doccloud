<?php
/** Slice 6 proof 8 — the worker: the order of the passes, a step that throws (cron.step_failed, the pass goes on), worker_passes.steps with counts and milliseconds, --only, and "Run a pass now" from the admin screen. */
require __DIR__ . '/lib.php';
seed_texts();
$p = pdo();
require_once dirname(__DIR__, 3) . '/app/features/admin/passes.php';

echo "1. The order and the record\n";
$since = last_activity_id();
$rows0 = (int) one('SELECT count(*) FROM worker_passes');
$r = worker('upload_sessions_expire,extract_text,thumbnails,search_catch_up,graph_jobs,exports,versions_expire,trash_purge,blobs_free,links_expire,requests_close,locks_expire,quota_watch,outbox,housekeeping,dispatches,proposals,key_usage_prune');
ok(array_keys($r['ran'] ?? []) === WORKER_PASSES, 'every pass ran, in the order of passes.php: ' . implode(' ', array_keys($r['ran'] ?? [])));
ok(WORKER_PASSES === ['upload_sessions_expire', 'extract_text', 'thumbnails', 'search_catch_up', 'graph_jobs', 'exports', 'versions_expire', 'trash_purge', 'blobs_free', 'links_expire', 'requests_close', 'locks_expire', 'quota_watch', 'outbox', 'housekeeping', 'dispatches', 'proposals', 'key_usage_prune'], 'the order: uploads, extract, thumbs, search, graph, exports, versions, trash, blobs, links, requests, locks, quota, outbox, housekeeping, then slices 7–8\'s');
ok($r['errors'] === [], 'no step failed');
$row = q('SELECT * FROM worker_passes ORDER BY id DESC LIMIT 1')[0];
$steps = json_decode($row['steps'], true);
ok((int) one('SELECT count(*) FROM worker_passes') === $rows0 + 1, 'one worker_passes row per pass');
$names = array_keys($steps); sort($names); $want = WORKER_PASSES; sort($want);
ok($names === $want, 'steps names every pass');
$bad = array_filter($steps, fn ($s) => !is_int($s['count']) || !is_int($s['ms']) || $s['ms'] < 0);
ok($bad === [], 'each step has an integer count and milliseconds');
ok($row['error'] === null && $row['finished_at'] !== null, 'no error; finished_at set');
$ev = q("SELECT * FROM activity_log WHERE action = 'cron.run' AND id > :s ORDER BY id DESC LIMIT 1", ['s' => $since])[0] ?? null;
$a = $ev ? json_decode($ev['after'], true) : [];
ok($ev !== null && $ev['source'] === 'cron' && count($a['ran']) === count(WORKER_PASSES) && $a['failed'] === 0 && isset($a['count'], $a['seconds']), 'cron.run logged with the steps, the count and the seconds');
ok((int) one("SELECT count(*) FROM activity_log WHERE action = 'worker.pass' AND id > :s", ['s' => $since]) === 0, 'the old worker.pass row is gone (cron.run replaces it)');

echo "2. A step that throws\n";
$seen = last_activity_id();
$d = seed_doc($s = (int) one("SELECT root_folder_id FROM libraries WHERE kind = 'personal' AND owner_member_id = 26"), 'w6-throw.pdf', 26, 'x');
$p->exec("UPDATE documents SET trashed_at = now() - interval '40 days', trashed_by = 26, trashed_from_folder_id = folder_id WHERE id = $d");
$out = shell_exec('cd ' . escapeshellarg(dirname(__DIR__, 3)) . ' && DC_WORKER_FAIL=outbox php bin/worker.php --passes=versions_expire,trash_purge,outbox,housekeeping 2>&1; echo "exit=$?"');
$lines = array_values(array_filter(explode("\n", (string) $out)));
$exit = (int) substr((string) end($lines), 5);
$r = json_decode($lines[count($lines) - 2], true) ?: [];
ok($exit === 1 && count($r['errors'] ?? []) === 1 && str_starts_with($r['errors'][0], 'outbox:'), 'the pass exits 1 and names the failed step');
ok(isset($r['ran']['trash_purge']) && isset($r['ran']['housekeeping']) && !isset($r['ran']['outbox']), 'the steps before AND after it still ran');
ok(!exists_doc($d), 'and did their work (the aged trash was purged)');
$ev = q("SELECT * FROM activity_log WHERE action = 'cron.step_failed' AND id > :s ORDER BY id DESC LIMIT 1", ['s' => $seen])[0] ?? null;
ok($ev !== null && json_decode($ev['after'], true)['step'] === 'outbox' && $ev['source'] === 'cron', 'cron.step_failed logged with the step');
$row = q('SELECT * FROM worker_passes ORDER BY id DESC LIMIT 1')[0];
$steps = json_decode($row['steps'], true);
ok($row['error'] !== null && str_contains($row['error'], 'outbox') && isset($steps['outbox']['error']) && !isset($steps['housekeeping']['error']), 'worker_passes keeps the error and marks only that step');
$ev = q("SELECT * FROM activity_log WHERE action = 'cron.run' ORDER BY id DESC LIMIT 1")[0];
ok(json_decode($ev['after'], true)['failed'] === 1, 'cron.run counts the failure');

echo "3. --only\n";
$rows0 = (int) one('SELECT count(*) FROM worker_passes');
$r = worker('outbox');
ok(array_keys($r['ran']) === ['outbox'] && array_keys($r['steps']) === ['outbox'], '--passes=outbox runs the one step');
$out = shell_exec('cd ' . escapeshellarg(dirname(__DIR__, 3)) . ' && php bin/worker.php --only=housekeeping 2>&1');
$r = json_decode(trim((string) $out), true) ?: [];
ok(array_keys($r['ran'] ?? []) === ['housekeeping'], '--only=housekeeping is the same');
$out = shell_exec('cd ' . escapeshellarg(dirname(__DIR__, 3)) . ' && php bin/worker.php --only=nonsense 2>&1; echo "exit=$?"');
ok(str_contains((string) $out, 'Unknown pass') && str_contains((string) $out, 'exit=2'), 'an unknown step is refused (exit 2)');
ok((int) one('SELECT count(*) FROM worker_passes') === $rows0 + 2, 'each run left its row');

echo "4. The worker screen\n";
$j = get_json(1, '/admin/worker');
$d = $j['json']['data'] ?? [];
ok($j['code'] === 200 && count($d['passes'] ?? []) >= 4 && ($d['steps'] ?? []) === WORKER_PASSES, 'JSON: the passes and the step names');
$failed = array_values(array_filter($d['passes'], fn ($x) => $x['status'] === 'danger'));
ok(count($failed) >= 1 && $failed[0]['steps']['outbox']['status'] === 'danger' && $failed[0]['steps']['housekeeping']['status'] === 'success', 'a failed pass is danger, with its failed step danger and the others success');
ok(isset($d['queues']['outbox_queued'], $d['queues']['blobs_to_free'], $d['queues']['trash_due']) && $d['windows']['trash_days'] === 30, 'the queues at a glance and the windows in force');
$b = page(actor(1), '/admin/worker')['body'];
ok(str_contains($b, 'id="worker-passes"') && str_contains($b, 'id="worker-run-btn"') && str_contains($b, 'id="worker-queue-outbox_queued"') && preg_match('/outbox \d+ · \d+ ms/', $b) === 1, 'the page: the passes with step chips "name count · ms", the queues, Run a pass now');
$j = get_json(1, '/admin/worker?limit=2');
ok(count($j['json']['data']['passes']) === 2, '?limit= limits the list');
ok(page(actor(27), '/admin/worker')['code'] === 403 && page(actor(26), '/admin/worker')['code'] === 403, 'a curator and a member get 403');
$q0 = (int) one("SELECT count(*) FROM notification_outbox WHERE status = 'failed'");
ok(($d['queues']['outbox_failed'] ?? -1) === $q0, 'outbox_failed counts the failed mail');

echo "5. Run a pass now\n";
$rows0 = (int) one('SELECT count(*) FROM worker_passes');
$r = post_json(1, '/admin/worker/run.php', ['step' => 'housekeeping']);
ok($r['code'] === 200 && ($r['json']['ok'] ?? false) && array_keys($r['json']['ran'] ?? []) === ['housekeeping'] && $r['json']['step'] === 'housekeeping' && $r['json']['busy'] === false, 'worker_run for one step: ok, the step\'s report');
ok((int) one('SELECT count(*) FROM worker_passes') === $rows0 + 1, 'the pass is on the list');
$ev = last_event('worker.run');
ok($ev !== null && (int) $ev['actor_member_id'] === 1 && json_decode($ev['after'], true)['step'] === 'housekeeping', 'worker.run logged with the admin and the step');
$r = post_json(1, '/admin/worker/run.php', []);
ok($r['code'] === 200 && count($r['json']['ran'] ?? []) === count(WORKER_PASSES) && $r['json']['step'] === 'all', 'with no step: every pass, in order');
ok(str_contains((string) $r['json']['location'], 'notice=ran'), 'it lands on the worker screen with a notice');
ok(post_json(1, '/admin/worker/run.php', ['step' => 'nonsense'])['code'] === 422, 'an unknown step: 422 on the field');
ok(post_json(27, '/admin/worker/run.php', [])['code'] === 403 && post_json(26, '/admin/worker/run.php', [])['code'] === 403, 'a curator and a member: 403');
ok(post_agent(40, 6401, '/admin/worker/run.php', [])['code'] === 403, 'an agent: 403 (people only)');
$reg = json_decode(file_get_contents(dirname(__DIR__, 3) . '/mcp/action_registry.json'), true);
$wr = null; foreach ($reg['actions'] as $x) { if ($x['action'] === 'worker_run') { $wr = $x; } }
ok($wr !== null && $wr['built'] === true && $wr['agent'] === false, 'the registry: worker_run is built and people-only');
$r = post(1, '/admin/worker/run.php', ['step' => 'housekeeping']);
ok(in_array($r['code'], [200, 302], true), 'the form post lands (HTML)');
echo "   another pass already running\n";
$other = new PDO(getenv('DB_DSN') ?: ('pgsql:host=' . (getenv('DB_HOST') ?: '127.0.0.1') . ';port=' . (getenv('DB_PORT') ?: '5432') . ';dbname=' . getenv('DB_NAME')), getenv('DB_USER'), getenv('DB_PASSWORD'));
$other->query("SELECT pg_try_advisory_lock(hashtext('doccloud_worker'))");
$r = post_json(1, '/admin/worker/run.php', ['step' => 'housekeeping']);
ok($r['code'] === 200 && $r['json']['busy'] === true && str_contains($r['json']['did'], 'Another pass is running') && str_contains($r['json']['location'], 'ran_busy'), 'a pass holding the lock: the run says so and starts nothing');
$other->query("SELECT pg_advisory_unlock(hashtext('doccloud_worker'))");
$r = post_json(1, '/admin/worker/run.php', ['step' => 'housekeeping']);
ok($r['json']['busy'] === false, 'the lock released: it runs again');
finish();

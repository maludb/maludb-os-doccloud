<?php
/**
 * Slice 8 proof 3 — the proposals screen and clerk_proposal_decide: mine to decide, a curator sees every one, accept applies a tags proposal's chosen tags as the decider (source agent), dismiss closes and is
 * remembered for 28 days, the walls (another member's proposal is "Not found."; the Clerk does not decide), a proposal expires with the housekeeping, the folder strip, the home card.
 */
require __DIR__ . '/lib.php';
$w = world();
$p = pdo();
$run = 8300;
$propose = function (array $f) use (&$run): array { $r = post_agent(CLERK, $run++, '/agents/propose.php', $f); return ['id' => (int) ($r['json']['record_id'] ?? 0), 'r' => $r]; };
$pClient = new_folder($w['board_root'], 'W8 P Client', 27);
$pInbox = new_folder($w['board_root'], 'W8 P Inbox', 27);
seed_doc($pInbox, 'w8-p-loose.pdf', 27, 'loose');
$p->exec("INSERT INTO folder_access (folder_id, principal_kind, principal_id, level, granted_by, created_at) VALUES ($pClient, 'guest', 29, 'view', 27, now() - interval '100 days') ON CONFLICT DO NOTHING");
$pr1 = seed_doc($w['priya_root'], 'w8-p1.pdf', 26, 'Proposal one. ' . WORLD_SECRET);
$pr2 = seed_doc($w['priya_root'], 'w8-p2.pdf', 26, 'Proposal two. ' . WORLD_SECRET);
$pr3 = seed_doc($w['priya_root'], 'w8-p3.pdf', 26, 'Proposal three. ' . WORLD_SECRET);
$a = $propose(['kind' => 'tags', 'title' => 'Tag w8-p1.pdf: alpha-tag, beta-tag', 'for_member' => 26, 'document' => $pr1, 'payload' => json_encode(['tags' => ['alpha-tag', 'beta-tag']])]);
$b = $propose(['kind' => 'tags', 'title' => 'Tag w8-p2.pdf: gamma-tag', 'for_member' => 26, 'document' => $pr2, 'payload' => json_encode(['tags' => ['gamma-tag']])]);
$c = $propose(['kind' => 'duplicate', 'title' => '2 copies of w8-p3.pdf', 'for_member' => 26, 'document' => $pr3, 'payload' => json_encode(['copies' => 2, 'document_ids' => [$pr3]])]);
$d = $propose(['kind' => 'tags', 'title' => 'Tag for-ann.pdf: nosy', 'for_member' => 26, 'document' => $w['guest_doc'], 'payload' => json_encode(['tags' => ['nosy']])]);
$e = $propose(['kind' => 'stale_share', 'title' => 'Ann has had access to W8 Client for 100 days', 'for_member' => 27, 'folder' => $pClient, 'key' => 'guest:29', 'payload' => json_encode(['guest_member_id' => 29, 'days' => 100])]);
$f = $propose(['kind' => 'untagged', 'title' => '3 documents in W8 Inbox have no tags', 'for_member' => 27, 'folder' => $pInbox, 'key' => 'folder:' . $pInbox, 'payload' => json_encode(['count' => 3])]);
ok($a['id'] > 0 && $b['id'] > 0 && $c['id'] > 0 && $d['id'] > 0 && $e['id'] > 0 && $f['id'] > 0, 'six proposals made by the Clerk for Priya and Marco');

echo "1. The screen: mine, a curator's, the others'\n";
$j = get_json(26, '/curate/proposals');
$mine = $j['json']['data']['proposals'] ?? [];
$ids = array_column($mine, 'proposal_id');
ok($j['code'] === 200 && in_array($a['id'], $ids, true) && in_array($b['id'], $ids, true) && in_array($c['id'], $ids, true), 'Priya sees hers');
ok(!in_array($e['id'], $ids, true) && !in_array($f['id'], $ids, true), '...and not Marco\'s');
ok(count(array_filter($mine, fn ($x) => (int) $x['for_member_id'] !== 26)) === 0, 'every one is for her');
$one = array_values(array_filter($mine, fn ($x) => $x['proposal_id'] === $a['id']))[0];
ok($one['kind'] === 'tags' && $one['payload']['tags'] === ['alpha-tag', 'beta-tag'] && $one['document_name'] === 'w8-p1.pdf' && $one['land'] === '/documents/' . $pr1 && $one['status'] === 'proposed', 'a card has the kind, the tags, the document\'s name and where to act');
ok(($j['json']['data']['curator'] ?? true) === false, 'she is not a curator');
$j = get_json(27, '/curate/proposals');
$ids = array_column($j['json']['data']['proposals'] ?? [], 'proposal_id');
ok(in_array($a['id'], $ids, true) && in_array($e['id'], $ids, true) && in_array($f['id'], $ids, true) && ($j['json']['data']['curator'] ?? false), 'a curator (Marco) sees every open proposal');
$j = get_json(27, '/curate/proposals?mine=1');
$ids = array_column($j['json']['data']['proposals'] ?? [], 'proposal_id');
ok(in_array($e['id'], $ids, true) && !in_array($a['id'], $ids, true), '...and "Only mine" narrows to his');
$j = get_json(27, '/curate/proposals?kind=duplicate');
ok(count(array_unique(array_column($j['json']['data']['proposals'] ?? [], 'kind'))) === 1 && in_array($c['id'], array_column($j['json']['data']['proposals'], 'proposal_id'), true), 'a kind filter');
$j = get_json(28, '/curate/proposals');
ok($j['code'] === 200 && ($j['json']['data']['proposals'] ?? ['x']) === [], 'Bea (nothing for her, not a curator) sees an empty list');
$j = get_json(29, '/curate/proposals');
ok($j['code'] === 403, 'a guest is refused: 403');
$x = req('GET', '/curate/proposals', ['headers' => ['Accept: application/json']]);
ok($x['code'] === 401, 'no session: 401');
$x = req('GET', '/curate/proposals', ['headers' => as_agent(run_token(EXPERT, 8350))]);
ok($x['code'] === 200 && (json_decode($x['body'], true)['data']['proposals'] ?? ['x']) === [], 'an agent (the expert) reads the screen under a run token and sees none that are for it');
$x = page(actor(1), '/proposals');
ok($x['code'] === 200 && str_contains($x['body'], 'id="proposal-card-' . $a['id'] . '"'), '/proposals is the same screen');
$html = page(actor(26), '/curate/proposals')['body'];
foreach (['proposal-card-' . $a['id'], 'proposal-accept-btn-' . $a['id'], 'proposal-dismiss-btn-' . $a['id'], 'proposal-' . $a['id'] . '-tag-alpha-tag', 'proposal-' . $a['id'] . '-tag-beta-tag', 'proposals-tabs', 'proposals-filters', 'proposal-kind-' . $a['id']] as $id) { ok(str_contains($html, 'id="' . $id . '"'), "the page has #$id"); }
ok(!str_contains($html, 'id="proposal-card-' . $e['id'] . '"') && !str_contains($html, WORLD_SECRET), '...and not Marco\'s card, nor a document\'s words');
ok(str_contains(page(actor(26), '/')['body'], 'href="/curate/proposals"'), 'the menu links to Proposals');
ok(!str_contains(page(actor(29), '/')['body'], 'href="/curate/proposals"'), '...but not for a guest');

echo "2. Deciding: the walls\n";
$x = post_json(28, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'dismiss']);
ok($x['code'] === 404 && ($x['json']['error']['message'] ?? '') === 'Not found.', 'Bea cannot decide Priya\'s proposal: "Not found." (404)');
$x = post_json(30, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'accept']);
ok($x['code'] === 404, 'nor Dana: 404');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $e['id'], 'decision' => 'dismiss']);
ok($x['code'] === 404, 'Priya cannot decide Marco\'s: 404');
$x = post_agent(CLERK, 8360, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'accept']);
ok($x['code'] === 403, 'the Clerk proposes and does not decide: 403');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => 99999999, 'decision' => 'accept']);
ok($x['code'] === 404, 'a proposal that does not exist: 404');
$x = post_json(26, '/curate/proposals/decide.php', ['decision' => 'accept']);
ok($x['code'] === 422, 'no proposal named: 422');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'maybe']);
ok($x['code'] === 422, 'a decision that is neither: 422');
ok(proposals('id = :i', ['i' => $a['id']])[0]['status'] === 'proposed', 'nothing changed through all of that');
$x = req('POST', '/curate/proposals/decide.php', ['headers' => ['Accept: application/json'], 'form' => ['proposal' => $a['id'], 'decision' => 'accept']]);
ok($x['code'] === 401, 'no session: 401');

echo "3. Accepting a tags proposal applies the chosen tags as the decider\n";
$since = last_activity_id(); $notes0 = (int) one('SELECT count(*) FROM notifications');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'accept', 'tags' => ['alpha-tag']]);
ok($x['code'] === 200 && ($x['json']['applied'] ?? 0) === 1 && ($x['json']['decision'] ?? '') === 'accept', 'accept with one of the two tags: applied 1');
ok(tags_of($pr1) === ['alpha-tag'], 'the document carries alpha-tag only');
$dt = q('SELECT dt.added_by, dt.source FROM document_tags dt JOIN tags t ON t.id = dt.tag_id WHERE dt.document_id = :d AND t.slug = \'alpha-tag\'', ['d' => $pr1])[0] ?? [];
ok((int) ($dt['added_by'] ?? 0) === 26 && ($dt['source'] ?? '') === 'agent', 'applied by Priya (the decider) with source agent');
$row = proposals('id = :i', ['i' => $a['id']])[0];
ok($row['status'] === 'accepted' && (int) $row['decided_by'] === 26 && $row['decided_at'] !== null && payload_of($row)['applied'] === ['alpha-tag'], 'the proposal is accepted by her and records what was applied');
$ev = activity('clerk.decide', $since)[0] ?? null; $ea = json_decode($ev['after'] ?? '{}', true);
ok($ev !== null && (int) $ev['actor_member_id'] === 26 && $ea['decision'] === 'accept' && $ea['applied'] === 1 && (int) $ev['document_id'] === $pr1, 'logged clerk.decide with the decision and the count');
ok((int) one('SELECT count(*) FROM notifications') === $notes0, 'an accept tells nobody');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $a['id'], 'decision' => 'accept']);
ok($x['code'] === 422 && str_contains($x['json']['error']['message'] ?? '', 'already'), 'deciding again: 422 "already decided"');
ok(tags_of($pr1) === ['alpha-tag'], '...and nothing more applied');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $b['id'], 'decision' => 'accept', 'tags' => ['not-offered']]);
ok($x['code'] === 422 && str_contains($x['json']['error']['message'] ?? '', 'Choose'), 'a tag the Clerk did not suggest: 422');
ok(proposals('id = :i', ['i' => $b['id']])[0]['status'] === 'proposed', '...and the proposal stays open');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $b['id'], 'decision' => 'accept']);
ok($x['code'] === 200 && tags_of($pr2) === ['gamma-tag'], 'no choice sent: all the suggested tags');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $d['id'], 'decision' => 'accept']);
ok($x['code'] === 404 && tags_of($w['guest_doc']) === ['base'], 'a tags proposal on a document she cannot see: 404, nothing applied');
ok(proposals('id = :i', ['i' => $d['id']])[0]['status'] === 'proposed', '...and it stays open');
$p->exec("INSERT INTO document_access (document_id, principal_kind, principal_id, level, granted_by) VALUES ({$w['guest_doc']}, 'member', 26, 'view', 27) ON CONFLICT DO NOTHING");
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $d['id'], 'decision' => 'accept']);
ok($x['code'] === 403 && !in_array('nosy', tags_of($w['guest_doc']), true), 'with view only she may not apply: 403 (edit is needed), nothing applied');

echo "4. Dismissing, and being left alone\n";
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $c['id'], 'decision' => 'dismiss', 'note' => 'they are the same on purpose']);
$row = proposals('id = :i', ['i' => $c['id']])[0];
ok($x['code'] === 200 && $row['status'] === 'dismissed' && (int) $row['decided_by'] === 26, 'dismiss closes it');
ok(last_event('clerk.decide') !== null && json_decode(last_event('clerk.decide')['after'], true)['note'] === 'they are the same on purpose', 'the note is logged');
$again = $propose(['kind' => 'duplicate', 'title' => '2 copies of w8-p3.pdf', 'for_member' => 26, 'document' => $pr3, 'payload' => '{}']);
ok(($again['r']['json']['proposed'] ?? true) === false, 'the Clerk is not allowed to ask again straight away');
$p->exec("UPDATE clerk_proposals SET decided_at = now() - interval '29 days', created_at = now() - interval '29 days' WHERE id = {$c['id']}");
$again = $propose(['kind' => 'duplicate', 'title' => '2 copies of w8-p3.pdf', 'for_member' => 26, 'document' => $pr3, 'payload' => '{}']);
ok(($again['r']['json']['proposed'] ?? false) === true, 'after 28 days it may');
$x = post_json(27, '/curate/proposals/decide.php', ['proposal' => $e['id'], 'decision' => 'accept']);
$row = proposals('id = :i', ['i' => $e['id']])[0];
ok($x['code'] === 200 && $row['status'] === 'accepted' && str_contains($x['json']['location'] ?? '', '/folders/' . $pClient . '/share'), 'accepting a stale-share proposal records it and lands on the folder\'s Share screen');
ok(count(array_filter(access_of('folder', $pClient), fn ($r) => $r['principal_kind'] === 'guest')) === 1, '...and removed nothing (an accept never changes a share)');
$x = post_json(27, '/curate/proposals/decide.php', ['proposal' => $again['id'], 'decision' => 'dismiss']);
$row = proposals('id = :i', ['i' => $again['id']])[0];
ok($x['code'] === 200 && (int) $row['decided_by'] === 27, 'a curator may decide a proposal that is for someone else');
$j = get_json(26, '/curate/proposals?status=accepted'); $ids = array_column($j['json']['data']['proposals'], 'proposal_id');
ok(in_array($a['id'], $ids, true) && !in_array($c['id'], $ids, true), 'the Accepted tab lists the accepted');
$j = get_json(26, '/curate/proposals?status=dismissed'); $ids = array_column($j['json']['data']['proposals'], 'proposal_id');
ok(in_array($c['id'], $ids, true), '...and the Dismissed tab the dismissed');
$x = $j['json']['data']['proposals'][0];
ok($x['decided_by_name'] !== null && $x['decided_at'] !== null, 'a decided card says by whom and when');

echo "5. Expiry\n";
$old = $propose(['kind' => 'locked', 'title' => 'An old lock', 'for_member' => 26, 'document' => $pr3, 'payload' => '{}']);
$p->exec("UPDATE clerk_proposals SET created_at = now() - interval '45 days' WHERE id = {$old['id']}");
worker('housekeeping');
ok(proposals('id = :i', ['i' => $old['id']])[0]['status'] === 'expired', 'an undecided proposal 45 days old is expired by the housekeeping');
$x = post_json(26, '/curate/proposals/decide.php', ['proposal' => $old['id'], 'decision' => 'accept']);
ok($x['code'] === 422, '...and can no longer be decided');

echo "6. The folder strip and the home card\n";
$j = get_json(27, '/folders/' . $pInbox);
ok(($j['json']['data']['proposals_open'] ?? -1) >= 1, 'the folder says it has an open proposal from the Clerk (Marco)');
$html = page(actor(27), '/f/' . $pInbox)['body'];
ok(str_contains($html, 'id="folder-proposals-strip"') && str_contains($html, 'id="folder-proposals-count"') && str_contains($html, 'id="folder-ask-expert-btn"'), 'the page shows the strip, the count and "Ask the expert to tag"');
$html = page(actor(26), '/f/' . $pInbox)['body'];
ok(!str_contains($html, 'id="folder-proposals-count"'), 'Priya, to whom none of the folder\'s proposals belongs, sees no count');
$j = get_json(26, '/');
$open = (int) one("SELECT count(*) FROM clerk_proposals WHERE status = 'proposed' AND for_member_id = 26");
ok(($j['json']['data']['proposals_open'] ?? -1) === $open && $open >= 1, "the home counts her open proposals ($open)");
$html = page(actor(26), '/')['body'];
ok(str_contains($html, 'id="home-clerk"') && str_contains($html, 'id="home-clerk-open"'), 'the home shows the Clerk card with her count');
$p->exec("INSERT INTO notifications (member_id, kind, title, body) VALUES (26, 'monday_note', 'Monday note: SMOKE Board has 4 things for you to look at', 'x')");
$j = get_json(26, '/');
ok(str_contains($j['json']['data']['clerk_note']['title'] ?? '', 'Monday note'), 'the home carries the Clerk\'s last Monday note');
finish();

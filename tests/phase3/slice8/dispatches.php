<?php
/**
 * Slice 8 proof 4 — the dispatch loop: the three triggers (forty untagged documents in a folder in a day, uploads on a file request, a file kept five times) make a dispatch for the person it concerns; the
 * worker sends each as ONE chat turn to the kernel's chat endpoint as the expert; answered (a 200-character excerpt) / awaiting an approval / refused / failed with the wait and three attempts; Retry and
 * Cancel; the people's own ask (tags_propose_request); the Agents screen's list; who sees which dispatch.
 */
require __DIR__ . '/lib.php';
$w = world();
$p = pdo();
chat_answers(chat_reply(str_repeat('The expert looked at the folder and found nothing odd. ', 8)));
chat_log_clear();
$p->exec('DELETE FROM agent_dispatches');
$p->exec('UPDATE libraries SET quota_bytes = NULL WHERE quota_bytes IS NOT NULL');             // the world filled the Board\'s library to 92% for the report; uploads here need room

echo "1. Nothing without an expert\n";
$p->exec('UPDATE dc_settings SET expert_member_id = NULL WHERE id = 1');
$r = worker('dispatches');
ok(($r['ran']['dispatches']['skipped'] ?? '') === 'no_expert_named' && chat_log() === [], 'no expert named: the pass does nothing and sends nothing');
name_agents();

echo "2. Forty untagged documents in a folder within a day\n";
$batch = new_folder(root_of(27), 'W8 Batch', 27);
$few = new_folder(root_of(27), 'W8 Few', 27);
for ($i = 1; $i <= 39; $i++) { seed_doc($batch, "w8-b-$i.pdf", 27, "Batch $i " . WORLD_SECRET); }
for ($i = 1; $i <= 39; $i++) { seed_doc($few, "w8-f-$i.pdf", 27, "Few $i"); }
$r = worker('dispatches');
ok(($r['ran']['dispatches']['made'] ?? -1) === 0 && dispatches("kind = 'untagged_batch'") === [], '39 untagged in a folder: no dispatch');
seed_doc($batch, 'w8-b-40.pdf', 27, 'Batch 40');
$r = worker('dispatches');
$d = dispatch_by_kind('untagged_batch', $batch);
ok($d !== null && ($r['ran']['dispatches']['made'] ?? 0) === 1, 'the 40th makes ONE untagged_batch dispatch');
ok((int) $d['agent_member_id'] === EXPERT && $d['via'] === 'chat' && (int) $d['acting_member_id'] === 27 && (int) $d['folder_id'] === $batch, 'to the expert, by chat, acting for the folder\'s owner Marco');
ok($d['status'] === 'answered' && (int) $d['attempts'] === 1 && $d['answered_at'] !== null && (int) $d['run_id'] === 11, 'sent in the same pass: answered, one attempt, the run recorded');
ok(mb_strlen((string) $d['reply_excerpt']) === 200, 'the reply is kept as a 200-character excerpt (' . mb_strlen((string) $d['reply_excerpt']) . ')');
$log = chat_log();
ok(count($log) === 1 && $log[0]['agent'] === 'expert' && $log[0]['acting'] === '27', 'the fake kernel was asked ONE turn, as the expert, acting for member 27');
ok(str_contains($log[0]['utterance'], 'W8 Batch') && str_contains($log[0]['utterance'], '40 documents') && str_contains($log[0]['utterance'], 'tag_propose'), 'the turn names the folder, the count and what to do');
ok(!str_contains($log[0]['utterance'], WORLD_SECRET) && !str_contains($log[0]['utterance'], 'Batch 1'), '...and holds no document\'s words');
$names = activity('agent.dispatch', 0); $last = end($names);
ok($last !== false && $last['source'] === 'cron' && (int) $last['folder_id'] === $batch && json_decode($last['after'], true)['kind'] === 'untagged_batch', 'logged agent.dispatch (source cron) with the folder');
$rep = last_event('agent.reply');
ok($rep !== null && json_decode($rep['after'], true)['status'] === 'answered', 'and agent.reply');
$r = worker('dispatches');
ok(count(dispatches("kind = 'untagged_batch'")) === 1 && count(chat_log()) === 1, 'a second pass the same day makes and sends nothing more');
ok(dispatch_by_kind('untagged_batch', $few) === null, 'the folder with 39 never woke the expert');
$p->exec("UPDATE agent_dispatches SET created_at = now() - interval '25 hours' WHERE id = {$d['id']}");
worker('dispatches');
ok(count(dispatches("kind = 'untagged_batch' AND folder_id = $batch")) === 2, 'the next day, the folder still holding forty untagged makes another');
chat_log_clear();

echo "3. A file request receives an upload — and the expert reaches an action that waits for approval\n";
chat_answers(['run_id' => 12, 'status' => 'awaiting_approval', 'finished' => false, 'reply' => 'I would like to share the folder with the auditor, which needs approval.', 'approval_request_id' => 77, 'actions' => []]);
$m = make_request(27, ['folder' => $w['inbox'], 'label' => 'w8 invoices in', 'message' => 'Drop invoices here']);
$inv = fx_write('w8-invoice-1.txt', 'Invoice one ' . WORLD_SECRET . fx_para(1, 100));
$u = pub_upload($m['path'] . '/upload', $inv, 'Acme Billing', 'w8up', $m['path']);
ok($u['code'] === 200 && ($u['json']['ok'] ?? false), 'a visitor uploads through the request');
$r = worker('dispatches');
$d = dispatch_by_kind('request_received', $w['inbox']);
ok($d !== null && (int) $d['record_id'] === $m['link_id'] && $d['record_type'] === 'link' && (int) $d['acting_member_id'] === 27, 'a request_received dispatch for the maker');
ok($d['status'] === 'awaiting_approval' && $d['request_id'] === '77' && (int) $d['run_id'] === 12 && str_contains((string) $d['detail'], '77'), 'the kernel paused an action: awaiting_approval with the request number 77');
ok(str_contains((string) $d['reply_excerpt'], 'approval'), '...and the reply\'s excerpt');
$log = chat_log();
ok(count($log) === 1 && str_contains($log[0]['utterance'], 'w8 invoices in') && !str_contains($log[0]['utterance'], WORLD_SECRET), 'the turn names the request and the folder, not the file');
chat_answers(chat_reply('Filed and tagged; the share was approved.', 12));
$r = worker('dispatches');
$d = dispatches('id = :i', ['i' => $d['id']])[0];
ok($d['status'] === 'answered' && ($r['ran']['dispatches']['polled'] ?? 0) >= 1, 'once the approval is decided the next pass polls the run and it is answered');
ok(count(chat_log()) === 2, '(the poll is a GET of the run, one more call to the kernel)');
$r = worker('dispatches');
ok(count(dispatches("kind = 'request_received'")) === 1, 'no second dispatch for the same upload');
$inv2 = fx_write('w8-invoice-2.txt', 'Invoice two ' . fx_para(1, 100));
pub_upload($m['path'] . '/upload', $inv2, 'Acme Billing', 'w8up', $m['path']);
$p->exec("UPDATE agent_dispatches SET created_at = now() - interval '2 hours' WHERE kind = 'request_received'");
worker('dispatches');
ok(count(dispatches("kind = 'request_received'")) === 2, 'a later upload (after the hour) makes another');

echo "4. A file kept five times; the kernel fails; the wait; three attempts; Retry\n";
$sha = hash('sha256', 'w8-five');
$five = []; foreach (['a', 'b', 'c', 'd', 'e'] as $l) { $five[] = doc_with_sha(root_of(27), "w8-five-$l.pdf", 27, $sha); }
foreach ($five as $x) { tag_doc($x, tag_id_of('base')); }
chat_answers(null, 500);
chat_log_clear();
$r = worker('dispatches');
$d = dispatch_by_kind('duplicates_found', root_of(27));
ok($d !== null && (int) $d['document_id'] === $five[0] && str_contains((string) $d['detail'], '5 copies') || ($d !== null && $d['status'] === 'failed'), 'five copies of one file make a duplicates_found dispatch (' . ($d['status'] ?? '?') . ')');
ok($d['status'] === 'failed' && (int) $d['attempts'] === 1 && str_contains((string) $d['detail'], 'not reachable'), 'the kernel answered 500: failed, one attempt, the reason kept');
$f = last_event('agent.fail'); ok($f !== null && (int) json_decode($f['after'], true)['http'] === 500, 'logged agent.fail with the HTTP status');
worker('dispatches');
ok((int) dispatches('id = :i', ['i' => $d['id']])[0]['attempts'] === 1, 'tried again at once? no: the wait (30 minutes) has not passed');
$p->exec("UPDATE agent_dispatches SET answered_at = now() - interval '31 minutes' WHERE id = {$d['id']}");
worker('dispatches');
$d2 = dispatches('id = :i', ['i' => $d['id']])[0];
ok($d2['status'] === 'failed' && (int) $d2['attempts'] === 2, 'after the wait it is tried again: attempt 2, failed again');
$p->exec("UPDATE agent_dispatches SET answered_at = now() - interval '31 minutes' WHERE id = {$d['id']}");
worker('dispatches');
$d2 = dispatches('id = :i', ['i' => $d['id']])[0];
ok($d2['status'] === 'failed' && (int) $d2['attempts'] === 3, 'attempt 3');
$sent = count(chat_log());
$p->exec("UPDATE agent_dispatches SET answered_at = now() - interval '5 hours' WHERE id = {$d['id']}");
worker('dispatches');
ok((int) dispatches('id = :i', ['i' => $d['id']])[0]['attempts'] === 3 && count(chat_log()) === $sent, 'and no more: three attempts is all');
$wait = (int) one("SELECT dispatch_retry_minutes FROM dc_settings WHERE id = 1");
ok($wait === 30, 'the wait is the setting (30 minutes)');
chat_answers(chat_reply('These five copies are the same invoice; the one in the Board root is the oldest.', 13));
$x = post_json(1, '/admin/agents/retry.php', ['dispatch' => $d['id']]);
$d2 = dispatches('id = :i', ['i' => $d['id']])[0];
ok($x['code'] === 200 && $d2['status'] === 'sent' && (int) $d2['attempts'] === 0 && $d2['run_id'] === null && $d2['detail'] === null, 'Retry puts it back in the queue with the attempts started again');
$ev = last_event('agent.retry'); ok($ev !== null && (int) $ev['actor_member_id'] === 1, 'logged agent.retry');
worker('dispatches');
$d2 = dispatches('id = :i', ['i' => $d['id']])[0];
ok($d2['status'] === 'answered' && str_contains((string) $d2['reply_excerpt'], 'same invoice'), 'the next pass sends it: answered');
$x = post_json(1, '/admin/agents/retry.php', ['dispatch' => $d['id']]);
ok($x['code'] === 422 && str_contains($x['json']['error']['message'] ?? '', 'answered'), 'an answered dispatch cannot be retried: 422');

echo "5. The kernel refuses; the kernel cannot be reached\n";
$m2 = make_request(27, ['folder' => $w['scans'], 'label' => 'w8 scans in']);
$p->exec("INSERT INTO link_opens (link_id, what, address_hash) VALUES ({$m2['link_id']}, 'upload', 'w8x1')");
chat_answers(null, 403, 'This person may not use the expert.');
worker('dispatches');
$d = dispatch_by_kind('request_received', $w['scans']);
ok($d['status'] === 'refused' && str_contains((string) $d['detail'], 'may not use the expert') && (int) $d['attempts'] === 1, 'a 403 from the kernel: refused, in its words');
$p->exec("UPDATE agent_dispatches SET answered_at = now() - interval '5 hours' WHERE id = {$d['id']}");
$n = count(chat_log());
worker('dispatches');
ok(dispatches('id = :i', ['i' => $d['id']])[0]['status'] === 'refused' && count(chat_log()) === $n, 'a refusal is not retried by itself');
chat_answers(chat_reply('Done.'));
post_json(1, '/admin/agents/retry.php', ['dispatch' => $d['id']]);
worker('dispatches');
ok(dispatches('id = :i', ['i' => $d['id']])[0]['status'] === 'answered', 'but a person\'s Retry sends it');
$m3 = make_request(27, ['folder' => $w['client'], 'label' => 'w8 client in']);
$p->exec("INSERT INTO link_opens (link_id, what, address_hash) VALUES ({$m3['link_id']}, 'upload', 'w8x2')");
$r = worker('dispatches', ['OS_APPLICATION_TOKEN' => '']);
$d = dispatch_by_kind('request_received', $w['client']);
ok($d['status'] === 'failed' && str_contains((string) $d['detail'], 'not reachable'), 'a kernel the application cannot reach (no token / no answer): failed, to try again');
chat_answers(chat_reply('Filed.'));
$p->exec("UPDATE agent_dispatches SET answered_at = now() - interval '31 minutes' WHERE id = {$d['id']}");
worker('dispatches');
ok(dispatches('id = :i', ['i' => $d['id']])[0]['status'] === 'answered', '...and once it is back the retry (after the wait) is answered');
chat_answers(null, 409);
$m4 = make_request(27, ['folder' => $few, 'label' => 'w8 few in']);
$p->exec("INSERT INTO link_opens (link_id, what, address_hash) VALUES ({$m4['link_id']}, 'upload', 'w8x3')");
worker('dispatches');
$d = dispatch_by_kind('request_received', $few);
ok($d['status'] === 'failed', 'a busy expert (409) is a failure to retry, not a refusal');
chat_answers(chat_reply('ok'));
post_json(1, '/admin/agents/cancel.php', ['dispatch' => $d['id']]);

echo "6. Asking the expert (tags_propose_request) and Cancel\n";
$p->exec("UPDATE agent_dispatches SET created_at = now() - interval '3 days'");
chat_log_clear();
$x = post_json(27, '/agents/propose-tags.php', ['folder' => $w['inbox']]);
$d = dispatch_by_kind('untagged_batch', $w['inbox']);
ok($x['code'] === 200 && (int) ($x['json']['record_id'] ?? 0) === (int) $d['id'] && $d['status'] === 'sent' && (int) $d['acting_member_id'] === 27 && $d['run_id'] === null, 'Marco asks: a queued untagged_batch dispatch acting for him');
$ev = last_event('agent.dispatch'); ok($ev !== null && (int) $ev['folder_id'] === $w['inbox'] && (int) $ev['actor_member_id'] === 27 && $ev['source'] === 'assistant', 'logged agent.dispatch by him');
$x = post_json(27, '/agents/propose-tags.php', ['folder' => $w['inbox']]);
ok($x['code'] === 422 && str_contains($x['json']['error']['message'] ?? '', 'already'), 'asking again at once: 422 (already on it)');
$x = post_json(30, '/agents/propose-tags.php', ['folder' => $w['inbox']]);
ok($x['code'] === 404, 'Dana, who cannot see the folder: 404');
$x = post_json(29, '/agents/propose-tags.php', ['folder' => $w['inbox']]);
ok(in_array($x['code'], [403, 404], true), 'a guest: refused (' . $x['code'] . ')');
$x = post_agent(EXPERT, 8400, '/agents/propose-tags.php', ['folder' => $w['inbox']]);
ok($x['code'] === 403, 'an agent may not ask (people only): 403');
$x = post_json(27, '/agents/propose-tags.php', ['folder' => $w['contracts']]);
ok($x['code'] === 422 && str_contains($x['json']['error']['message'] ?? '', 'already has tags'), 'a folder with nothing untagged: 422');
$x = post_json(27, '/agents/propose-tags.php', []);
ok($x['code'] === 422, 'no folder named: 422');
echo "   Cancel\n";
$x = post_json(26, '/admin/agents/cancel.php', ['dispatch' => $d['id']]);
ok($x['code'] === 403, 'a member may not cancel: 403');
$x = post_agent(EXPERT, 8401, '/admin/agents/cancel.php', ['dispatch' => $d['id']]);
ok($x['code'] === 403, 'nor an agent: 403');
$x = post_json(1, '/admin/agents/cancel.php', ['dispatch' => $d['id']]);
$d2 = dispatches('id = :i', ['i' => $d['id']])[0];
ok($x['code'] === 200 && $d2['status'] === 'refused' && str_contains((string) $d2['detail'], 'Cancelled by SMOKE Owner'), 'the admin cancels a queued dispatch: closed, with the canceller\'s name');
$ev = last_event('agent.dispatch_cancel'); ok($ev !== null && (int) $ev['actor_member_id'] === 1, 'logged agent.dispatch_cancel');
worker('dispatches');
ok(count(array_filter(chat_log(), fn ($t) => str_contains($t['utterance'] ?? '', 'W8 Inbox') && str_contains($t['utterance'] ?? '', 'no tags'))) === 0 && dispatches('id = :i', ['i' => $d['id']])[0]['status'] === 'refused' && (int) dispatches('id = :i', ['i' => $d['id']])[0]['attempts'] === 0, 'nothing is sent again');
$x = post_json(1, '/admin/agents/cancel.php', ['dispatch' => $d['id']]);
ok($x['code'] === 422, 'cancelling twice: 422');
$x = post_json(1, '/admin/agents/cancel.php', ['dispatch' => 99999999]);
ok($x['code'] === 404, 'a dispatch that does not exist: 404');
$x = post_json(1, '/admin/agents/retry.php', []);
ok($x['code'] === 422, 'retry with no dispatch named: 422');
$x = post_json(27, '/admin/agents/retry.php', ['dispatch' => $d['id']]);
ok($x['code'] === 403, 'a curator may not retry: 403');
$x = post_agent(EXPERT, 8402, '/admin/agents/retry.php', ['dispatch' => $d['id']]);
ok($x['code'] === 403, 'an agent may not retry (it holds no agents.settings): 403');

echo "7. The Agents screen and who sees a dispatch\n";
$j = get_json(1, '/admin/agents');
$rows = $j['json']['data']['dispatches'] ?? [];
ok(count($rows) >= 8 && $rows[0]['dispatch_id'] > $rows[count($rows) - 1]['dispatch_id'], 'the dispatches, newest first (' . count($rows) . ')');
$statuses = array_unique(array_column($rows, 'status'));
ok(in_array('answered', $statuses, true) && in_array('refused', $statuses, true), 'with their statuses');
$one = array_values(array_filter($rows, fn ($r) => $r['kind'] === 'request_received' && $r['folder_id'] === $w['inbox']))[0] ?? [];
ok($one['acting_name'] === 'SMOKE Marco' && $one['folder_name'] === 'W8 Inbox' && $one['reply_excerpt'] !== null, 'a row has who it acted for, the folder\'s name and the reply');
$j = get_json(1, '/admin/agents?status=refused');
ok(count(array_unique(array_column($j['json']['data']['dispatches'], 'status'))) === 1 && $j['json']['data']['dispatches'][0]['status'] === 'refused', 'the status filter');
$j = get_json(1, '/admin/agents?kind=duplicates_found');
ok(count($j['json']['data']['dispatches']) === 1, '...and the kind filter');
$html = page(actor(1), '/admin/agents')['body'];
ok(str_contains($html, 'id="dispatches-table"') && preg_match('/id="dispatch-retry-\d+"/', $html) === 1 && !str_contains($html, WORLD_SECRET), 'the table has Retry on a refused one, and no document\'s words');
$p->exec("SELECT set_config('app.member_id', '27', false)");
$mine27 = (int) one('SELECT count(*) FROM mcp_agent_dispatches');
$p->exec("SELECT set_config('app.member_id', '30', false)");
$mine30 = (int) one('SELECT count(*) FROM mcp_agent_dispatches');
$p->exec("SELECT set_config('app.member_id', '" . EXPERT . "', false)");
$minex = (int) one('SELECT count(*) FROM mcp_agent_dispatches');
$p->exec("SELECT set_config('app.member_id', '', false)");
ok($mine27 > 0 && $mine30 === 0 && $minex === (int) one('SELECT count(*) FROM agent_dispatches'), 'by the view: Marco sees the ones he is the acting person of, Dana none, the expert every one it was sent');
finish();

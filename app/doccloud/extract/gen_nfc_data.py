#!/usr/bin/env python3
"""Generate nfc_data.php — the canonical decomposition, combining-class and primary-composite
tables dc_nfc() uses when PHP's intl extension (Normalizer) is absent.

Run: python3 app/knowledge/extract/gen_nfc_data.py > app/knowledge/extract/nfc_data.php
The tables come from Python's unicodedata (the Unicode version is written into the file).
Hangul syllables are composed algorithmically in PHP and are not in the tables.
"""
import sys
import unicodedata as ud

S_BASE, S_COUNT = 0xAC00, 11172


def canon_decomp(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith('<'):
        return None
    return [int(x, 16) for x in d.split()]


def full_decomp(cp):
    d = canon_decomp(cp)
    if d is None:
        return [cp]
    out = []
    for x in d:
        out.extend(full_decomp(x))
    return out


decomp, ccc, comp = {}, {}, {}
for cp in range(0x110000):
    if S_BASE <= cp < S_BASE + S_COUNT:
        continue
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = ud.combining(chr(cp))
    if c:
        ccc[cp] = c
    d = canon_decomp(cp)
    if d is None:
        continue
    decomp[cp] = full_decomp(cp)
    if len(d) == 2 and ud.normalize('NFC', chr(d[0]) + chr(d[1])) == chr(cp):
        comp[d[0] * 0x110000 + d[1]] = cp

w = sys.stdout.write
w("<?php\ndeclare(strict_types=1);\n\n")
w("// Generated by gen_nfc_data.py from Unicode %s — do not edit by hand.\n" % ud.unidata_version)
w("return [\n'version' => '%s',\n" % ud.unidata_version)
w("'d' => [")
w(",".join("%d=>[%s]" % (k, ",".join(str(x) for x in v)) for k, v in sorted(decomp.items())))
w("],\n'c' => [")
w(",".join("%d=>%d" % (k, v) for k, v in sorted(ccc.items())))
w("],\n'p' => [")
w(",".join("%d=>%d" % (k, v) for k, v in sorted(comp.items())))
w("],\n];\n")
